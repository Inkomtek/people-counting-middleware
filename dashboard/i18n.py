def resolve_language(request):
    """?lang= wins (and is remembered by the view in a cookie), then the cookie, then Indonesian."""
    for value in (request.GET.get("lang"), request.COOKIES.get(LANGUAGE_COOKIE)):
        if value in LANGUAGES:
            return value
    return DEFAULT_LANGUAGE
