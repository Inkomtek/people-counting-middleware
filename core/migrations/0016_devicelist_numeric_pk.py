"""Give DeviceList a numeric primary key and move the device's own ID to an editable `device_id`.

Before: `id` (varchar) was both the device ID sent by ZK / the sensor API and the primary key, so it
could not be edited without breaking every row that points at the device. After: `id` is an
auto-increment bigint and `device_id` (unique, editable) holds the device ID. All foreign keys,
including the washroom ones, are rewired to the new numeric id; existing rows keep their device.

PostgreSQL only (the project runs on PostgreSQL), hence raw SQL inside SeparateDatabaseAndState.
"""

