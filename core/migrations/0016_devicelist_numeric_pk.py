def forward_sql():
    sql = [
        "ALTER TABLE core_devicelist ADD COLUMN device_id varchar(100);",
        "UPDATE core_devicelist SET device_id = id;",
        "ALTER TABLE core_devicelist ALTER COLUMN device_id SET NOT NULL;",
        # Existing rows get 1, 2, 3, ... from the identity sequence.
        "ALTER TABLE core_devicelist ADD COLUMN new_id bigint GENERATED BY DEFAULT AS IDENTITY;",
    ]
    for table, nullable, _, _ in REFERENCING:
        sql += [
            f"ALTER TABLE {table} ADD COLUMN device_new bigint;",
            f"UPDATE {table} t SET device_new = d.new_id FROM core_devicelist d WHERE d.id = t.device_id;",
            # Dropping the old varchar column also drops its FK constraint and indexes.
            f"ALTER TABLE {table} DROP COLUMN device_id;",
            f"ALTER TABLE {table} RENAME COLUMN device_new TO device_id;",
        ]
        if not nullable:
            sql.append(f"ALTER TABLE {table} ALTER COLUMN device_id SET NOT NULL;")
    sql += [
        "ALTER TABLE core_devicelist DROP COLUMN id;",
        "ALTER TABLE core_devicelist RENAME COLUMN new_id TO id;",
        "ALTER TABLE core_devicelist ADD CONSTRAINT core_devicelist_pkey PRIMARY KEY (id);",
        "ALTER TABLE core_devicelist ADD CONSTRAINT core_devicelist_device_id_key UNIQUE (device_id);",
        "CREATE INDEX core_devicelist_device_id_like ON core_devicelist (device_id varchar_pattern_ops);",
    ]
    for table, _, index, extra in REFERENCING:
        sql += [
            f"ALTER TABLE {table} ADD CONSTRAINT {table}_device_id_fk_core_devicelist_id FOREIGN KEY (device_id) "
            "REFERENCES core_devicelist (id) DEFERRABLE INITIALLY DEFERRED;",
            f"CREATE INDEX {index} ON {table} (device_id);",
            *extra,
        ]
    return sql


